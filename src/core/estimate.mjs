// `briefcut estimate`: every paid request the film needs, what the cache already holds, and the
// cost of the rest, written to out/COST.md before anything is sent.
import fs from 'node:fs';
import path from 'node:path';
import { plannedRequests } from './prepare.mjs';
import { AssetCache, stableJson } from './assets.mjs';
import { sha1, ensureDir, f2, readJson } from './util.mjs';

export async function estimateFilm({ cfg, filmDir, provider, videoProvider = null, log }) {
  const audioDir = path.join(filmDir, 'audio');
  const cache = new AssetCache(audioDir, { log, offline: true });
  const voices = readJson(path.join(audioDir, 'voices.json')) || {};
  const plan = plannedRequests(cfg, provider.name, { filmDir, voices });
  const rows = plan.map((p) => {
    // A request whose voice is not resolved yet cannot be matched by fingerprint; match by name.
    const fp = sha1(stableJson(p.request));
    const hit = Object.entries(cache.index).find(([k, m]) => k.replace(/\.[^.]+$/, '') === p.asset && (m.fingerprint === fp || !voices[p.cue?.voice?.toLowerCase()]));
    const usd = hit ? 0 : provider.price(p.request);
    return { asset: p.asset, kind: p.request.kind, detail: p.request.kind === 'tts' ? `"${p.request.text}" (${p.request.text.length} chars, ${p.request.model})` : `${p.request.seconds ?? '-'} s: ${String(p.request.prompt).slice(0, 70)}`, cached: !!hit, usd, credits: hit ? 0 : provider.credits ? provider.credits(p.request) : null };
  });
  let video = null;
  if (videoProvider && cfg.scenes.length && videoProvider.name !== 'handoff') {
    const per = await videoProvider.estimate({ seconds: 8, resolution: '1080p', model: cfg.video.model }).catch(() => null);
    video = { provider: videoProvider.name, perClip: per, clips: cfg.scenes.length, usd: per == null ? null : per * cfg.scenes.length };
  }
  const todo = rows.filter((r) => !r.cached);
  const total = todo.reduce((n, r) => n + r.usd, 0);
  const credits = todo.reduce((n, r) => n + (r.credits || 0), 0);
  const L = [
    `# Cost estimate: ${cfg.id}`,
    '',
    `Written ${new Date().toISOString()} by \`briefcut estimate\`, before any paid call. Audio provider \`${provider.name}\` (${provider.billing}).`,
    '',
    `- Requests needed: ${rows.length}; already in the cache: ${rows.length - todo.length}; to generate: ${todo.length}.`,
    `- Estimated audio cost of the rest: **${f2(total)} USD**${credits ? ` (${Math.round(credits)} credits)` : ''}.`,
    video ? `- Video (${video.provider}): ${video.clips} clips x ${video.perClip == null ? 'unknown' : `${f2(video.perClip)} USD`} = ${video.usd == null ? 'unknown' : `${f2(video.usd)} USD`}.` : '- Video: not generated by briefcut for this film (handoff or clips already in clips/).',
    `- Pricing basis: see docs/PROVIDERS.md. Retakes forced by caps or word cuts are not in this list; each costs one more line.`,
    '',
    '| Asset | Kind | Request | Cached | Est. USD |',
    '|---|---|---|---|---|',
    ...rows.map((r) => `| ${r.asset} | ${r.kind} | ${r.detail.replace(/\|/g, '/')} | ${r.cached ? 'yes' : 'no'} | ${r.cached ? '0' : r.usd.toFixed(4)} |`),
    '',
  ];
  ensureDir(path.join(filmDir, 'out'));
  fs.writeFileSync(path.join(filmDir, 'out', 'COST.md'), L.join('\n'));
  return { rows, total, credits, video };
}
